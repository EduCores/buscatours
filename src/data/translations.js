export const currencyRates = {
  USD: { symbol: "$", rate: 1 },
  CLP: { symbol: "Ch$", rate: 950 },
  ARS: { symbol: "AR$", rate: 900 },
  EUR: { symbol: "€", rate: 0.92 }
};

export const formatPrice = (priceInUSD, activeCurrency) => {
  const cfg = currencyRates[activeCurrency] || currencyRates.USD;
  const converted = priceInUSD * cfg.rate;
  if (activeCurrency === "CLP" || activeCurrency === "ARS") {
    return `${cfg.symbol}${Math.round(converted).toLocaleString()}`;
  }
  // Muestra hasta 2 decimales pero elimina los ceros finales (.00 → sin decimales, .50 → .5)
  const rounded = parseFloat(converted.toFixed(2));
  return `${cfg.symbol}${rounded.toLocaleString("en-US", { minimumFractionDigits: 0, maximumFractionDigits: 2 })}`;
};
